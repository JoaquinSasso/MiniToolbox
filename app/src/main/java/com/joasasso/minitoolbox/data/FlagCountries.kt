/**
 * País del minijuego Adivina la Bandera. La bandera no se guarda: se arma con los
 * dos indicadores regionales Unicode del código ISO 3166-1 alfa-2 (por ejemplo,
 * "AR" da la bandera argentina).
 */
data class FlagCountry(
    val isoCode: String,
    val nameEs: String,
    val nameEn: String,
) {
    val flag: String = buildString {
        isoCode.forEach { appendCodePoint(REGIONAL_INDICATOR_A + (it - 'A')) }
    }

    private companion object {
        const val REGIONAL_INDICATOR_A = 0x1F1E6
    }
}

